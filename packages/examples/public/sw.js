/**
 * Service Worker for Helix Video Editor
 * 
 * Provides offline functionality with caching strategies:
 * - Precache: Static assets (JS, CSS, fonts)
 * - Runtime cache: Videos, images, audio files
 * - Network-first: API calls, dynamic content
 * 
 * Uses Workbox for efficient caching management.
 */

// Import Workbox from CDN (will be replaced with local in production)
importScripts('https://storage.googleapis.com/workbox-cdn/releases/7.0.0/workbox-sw.js');

const { registerRoute } = workbox.routing;
const { CacheFirst, NetworkFirst, StaleWhileRevalidate } = workbox.strategies;
const { ExpirationPlugin } = workbox.expiration;
const { CacheableResponsePlugin } = workbox.cacheableResponse;
const { precacheAndRoute } = workbox.precaching;

// Service Worker version (increment on changes)
const CACHE_VERSION = 'v1.0.0';
const CACHE_NAME = `helix-cache-${CACHE_VERSION}`;

// Precache static assets (generated by build)
// This will be replaced by Vite plugin with actual file list
precacheAndRoute(self.__WB_MANIFEST || []);

/**
 * Cache Strategy 1: App Shell (Cache First)
 * HTML, CSS, JS files - fastest response from cache
 */
registerRoute(
  ({ request }) => 
    request.destination === 'document' ||
    request.destination === 'script' ||
    request.destination === 'style',
  new CacheFirst({
    cacheName: `${CACHE_NAME}-app-shell`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
);

/**
 * Cache Strategy 2: Images (Cache First with expiration)
 * Profile images, thumbnails, icons
 */
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: `${CACHE_NAME}-images`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 7 * 24 * 60 * 60, // 7 days
      }),
    ],
  })
);

/**
 * Cache Strategy 3: Videos (Cache First with size limit)
 * Video files - cache for offline editing
 */
registerRoute(
  ({ request }) => 
    request.destination === 'video' ||
    request.url.includes('.mp4') ||
    request.url.includes('.webm'),
  new CacheFirst({
    cacheName: `${CACHE_NAME}-videos`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [200],
      }),
      new ExpirationPlugin({
        maxEntries: 20, // Limit to 20 videos
        maxAgeSeconds: 7 * 24 * 60 * 60, // 7 days
        purgeOnQuotaError: true, // Auto-delete on storage limit
      }),
    ],
  })
);

/**
 * Cache Strategy 4: Audio (Cache First)
 * Audio files for video tracks
 */
registerRoute(
  ({ request }) => 
    request.destination === 'audio' ||
    request.url.includes('.mp3') ||
    request.url.includes('.wav') ||
    request.url.includes('.m4a'),
  new CacheFirst({
    cacheName: `${CACHE_NAME}-audio`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [200],
      }),
      new ExpirationPlugin({
        maxEntries: 30,
        maxAgeSeconds: 7 * 24 * 60 * 60, // 7 days
      }),
    ],
  })
);

/**
 * Cache Strategy 5: Fonts (Cache First)
 * Web fonts - long-term cache
 */
registerRoute(
  ({ request }) => request.destination === 'font',
  new CacheFirst({
    cacheName: `${CACHE_NAME}-fonts`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 30,
        maxAgeSeconds: 365 * 24 * 60 * 60, // 1 year
      }),
    ],
  })
);

/**
 * Cache Strategy 6: API Calls (Network First)
 * API requests - fresh data preferred
 */
registerRoute(
  ({ url }) => url.pathname.startsWith('/api/'),
  new NetworkFirst({
    cacheName: `${CACHE_NAME}-api`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 5 * 60, // 5 minutes
      }),
    ],
  })
);

/**
 * Cache Strategy 7: CDN Resources (Stale While Revalidate)
 * Third-party resources - balance speed and freshness
 */
registerRoute(
  ({ url }) => 
    url.origin === 'https://fonts.googleapis.com' ||
    url.origin === 'https://fonts.gstatic.com' ||
    url.origin === 'https://cdn.jsdelivr.net',
  new StaleWhileRevalidate({
    cacheName: `${CACHE_NAME}-cdn`,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
);

/**
 * Handle Service Worker activation
 * Clean up old caches
 */
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames
          .filter((cacheName) => {
            // Delete old version caches
            return cacheName.startsWith('helix-cache-') && 
                   cacheName !== CACHE_NAME;
          })
          .map((cacheName) => caches.delete(cacheName))
      );
    })
  );
});

/**
 * Handle offline fallback
 */
self.addEventListener('fetch', (event) => {
  // Skip non-GET requests
  if (event.request.method !== 'GET') return;
  
  event.respondWith(
    caches.match(event.request).then((response) => {
      return response || fetch(event.request).catch(() => {
        // Return offline page for navigation requests
        if (event.request.destination === 'document') {
          return caches.match('/offline.html');
        }
        
        // Return placeholder for images
        if (event.request.destination === 'image') {
          return caches.match('/icons/offline-placeholder.png');
        }
      });
    })
  );
});

/**
 * Handle messages from clients
 */
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
  
  if (event.data && event.data.type === 'CLIENTS_CLAIM') {
    self.clients.claim();
  }
});

console.log('Helix Service Worker loaded:', CACHE_VERSION);
